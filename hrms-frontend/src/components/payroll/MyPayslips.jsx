// src/components/payroll/MyPayslips.jsx
import { useState, useEffect } from 'react';
import { FileText, Eye, Download } from 'lucide-react';
import payrollService from '../../services/payrollService';
import { useAuth } from '../../context/AuthContext';
import PayslipView from './PayslipView';

const MyPayslips = () => {
  const { user } = useAuth();
  const [payslips, setPayslips] = useState([]);
  const [loading, setLoading] = useState(true);
  const [selectedPayslip, setSelectedPayslip] = useState(null);
  const [showPayslipView, setShowPayslipView] = useState(false);

  useEffect(() => {
    fetchPayslips();
  }, []);

  const fetchPayslips = async () => {
    try {
      setLoading(true);
      const data = await payrollService.getMyPayslips(user.id);
      setPayslips(data);
    } catch (error) {
      console.error('Failed to fetch payslips:', error);
      alert('Failed to load payslips');
    } finally {
      setLoading(false);
    }
  };

  const handleViewPayslip = (payslip) => {
    setSelectedPayslip(payslip);
    setShowPayslipView(true);
  };

  const getMonthName = (month) => {
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    return months[month - 1];
  };

  const getStatusBadge = (status) => {
    const styles = {
      GENERATED: 'bg-blue-100 text-blue-700',
      SENT: 'bg-yellow-100 text-yellow-700',
      PAID: 'bg-green-100 text-green-700'
    };

    return (
      <span className={`px-3 py-1 rounded-full text-xs font-semibold ${styles[status]}`}>
        {status}
      </span>
    );
  };

  if (loading) {
    return (
      <div className="flex items-center justify-center h-96">
        <div className="animate-spin rounded-full h-16 w-16 border-t-4 border-blue-500"></div>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-3xl font-bold text-gray-800">My Payslips</h1>
          <p className="text-gray-600 mt-1">View and download your salary slips</p>
        </div>
      </div>

      {/* Payslips Grid */}
      {payslips.length === 0 ? (
        <div className="bg-white rounded-xl shadow-md p-12 text-center">
          <FileText size={64} className="mx-auto text-gray-300 mb-4" />
          <h3 className="text-xl font-semibold text-gray-700 mb-2">No Payslips Found</h3>
          <p className="text-gray-500">Your payslips will appear here once generated by HR.</p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {payslips.map((payslip) => (
            <div
              key={payslip.id}
              className="bg-white rounded-xl shadow-md hover:shadow-xl transition-shadow overflow-hidden"
            >
              {/* Card Header */}
              <div className="bg-gradient-to-r from-green-500 to-blue-500 p-4 text-white">
                <div className="flex items-center justify-between mb-2">
                  <FileText size={32} />
                  {getStatusBadge(payslip.status)}
                </div>
                <h3 className="text-2xl font-bold">
                  {getMonthName(payslip.month)} {payslip.year}
                </h3>
              </div>

              {/* Card Body */}
              <div className="p-6">
                <div className="space-y-3 mb-6">
                  <div className="flex justify-between items-center pb-2 border-b">
                    <span className="text-sm text-gray-600">Gross Salary</span>
                    <span className="font-semibold text-gray-800">
                      ${payslip.grossSalary?.toLocaleString()}
                    </span>
                  </div>

                  <div className="flex justify-between items-center pb-2 border-b">
                    <span className="text-sm text-gray-600">Deductions</span>
                    <span className="font-semibold text-red-600">
                      -${payslip.totalDeductions?.toLocaleString()}
                    </span>
                  </div>

                  <div className="flex justify-between items-center pt-2">
                    <span className="text-sm font-bold text-gray-700">Net Salary</span>
                    <span className="text-2xl font-bold text-green-600">
                      ${payslip.netSalary?.toLocaleString()}
                    </span>
                  </div>
                </div>

                {/* Attendance Info */}
                <div className="bg-gray-50 rounded-lg p-3 mb-4">
                  <div className="grid grid-cols-3 gap-2 text-center text-xs">
                    <div>
                      <p className="text-gray-500">Working Days</p>
                      <p className="font-bold text-gray-800">{payslip.workingDays}</p>
                    </div>
                    <div>
                      <p className="text-gray-500">Present</p>
                      <p className="font-bold text-green-600">{payslip.presentDays}</p>
                    </div>
                    <div>
                      <p className="text-gray-500">Absent</p>
                      <p className="font-bold text-red-600">{payslip.absentDays}</p>
                    </div>
                  </div>
                </div>

                {/* Actions */}
                <div className="flex gap-2">
                  <button
                    onClick={() => handleViewPayslip(payslip)}
                    className="flex-1 flex items-center justify-center gap-2 bg-blue-500 hover:bg-blue-600 text-white font-semibold py-2 px-4 rounded-lg transition"
                  >
                    <Eye size={18} />
                    View
                  </button>
                  <button
                    className="flex-1 flex items-center justify-center gap-2 bg-green-500 hover:bg-green-600 text-white font-semibold py-2 px-4 rounded-lg transition"
                  >
                    <Download size={18} />
                    Download
                  </button>
                </div>

                <p className="text-xs text-gray-500 text-center mt-3">
                  Generated on {new Date(payslip.generatedDate).toLocaleDateString()}
                </p>
              </div>
            </div>
          ))}
        </div>
      )}

      {/* Payslip View Modal */}
      {showPayslipView && selectedPayslip && (
        <PayslipView
          payslip={selectedPayslip}
          onClose={() => {
            setShowPayslipView(false);
            setSelectedPayslip(null);
          }}
        />
      )}
    </div>
  );
};

export default MyPayslips;